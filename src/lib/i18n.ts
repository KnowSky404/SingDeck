export function translate(language: Language): Translate {
  return (message, values = {}) => {
    const template =
      language === "zh"
        ? (zh[message.replace(/\s+/g, " ").trim()] ?? message)
        : message;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      String(values[name] ?? match),
    );
  };
}
