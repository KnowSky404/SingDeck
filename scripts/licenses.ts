import {
  existsSync,
  readdirSync,
  readFileSync,
  writeFileSync,
  realpathSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import assert from "node:assert/strict";

const root = resolve(".");
const visited = new Set<string>();
const notices: string[] = [];
function collect(name: string, from: string) {
  let cursor = from;
  let manifest = "";
  while (true) {
    const candidate = join(cursor, "node_modules", name, "package.json");
    if (existsSync(candidate)) {
      manifest = realpathSync(candidate);
      break;
    }
    const parent = dirname(cursor);
    if (parent === cursor) break;
    cursor = parent;
  }
  if (!manifest || visited.has(manifest)) return;
  visited.add(manifest);
  const dir = dirname(manifest);
  const pkg = JSON.parse(readFileSync(manifest, "utf8"));
  const files = readdirSync(dir, { withFileTypes: true })
    .filter(
      (f) =>
        f.isFile() &&
        /^(license|licence|copying|ofl|notice)(\.|$)/i.test(f.name),
    )
    .sort((a, b) => a.name.localeCompare(b.name));
  const fallback = join(root, "licenses", `${name.replaceAll("/", "__")}.txt`);
  const license = files.length
    ? files.map((f) => readFileSync(join(dir, f.name), "utf8")).join("\n")
    : existsSync(fallback)
      ? readFileSync(fallback, "utf8")
      : `MISSING LICENSE TEXT: ${pkg.name}`;
  notices.push(
    `${pkg.name}@${pkg.version} (${pkg.license ?? "see license"})\n${license}`,
  );
  for (const dependency of Object.keys({
    ...pkg.dependencies,
    ...pkg.optionalDependencies,
  }))
    collect(dependency, dir);
}
const pkg = JSON.parse(readFileSync("package.json", "utf8"));
for (const dependency of Object.keys(pkg.dependencies))
  collect(dependency, root);
// The browser bundle includes Tailwind CSS and its Preflight stylesheet.
collect("tailwindcss", root);
assert(
  notices.some((n) => n.startsWith("react@")) &&
    notices.some((n) => n.startsWith("@fontsource-variable/geist@")) &&
    notices.some((n) => n.startsWith("tailwindcss@")),
  "Incomplete runtime license inventory",
);
assert(
  !notices.some((n) => n.includes("MISSING LICENSE TEXT")),
  notices.filter((n) => n.includes("MISSING LICENSE TEXT")).join("\n"),
);
const shadcn = readFileSync("licenses/shadcn-ui.txt", "utf8");
notices.push(`shadcn/ui source (MIT)\n${shadcn}`);
const singBoxNotice = readFileSync("proto/LICENSE.sing-box", "utf8");
const gpl = readFileSync("proto/LICENSE.GPL-3.0", "utf8");
notices.push(`sing-box protocol source (GPL-3.0-or-later)\n${singBoxNotice}\n${gpl}`);
writeFileSync(
  "public/third-party-licenses.txt",
  `SingDeck third-party notices. Generated by bun run licenses:generate.\n\n${notices.sort().join("\n\n" + "=".repeat(72) + "\n\n")}`.replace(
    /\r\n/g,
    "\n",
  ),
);
console.log(`Collected ${notices.length} third-party notices.`);
